from __future__ import annotations

from datetime import datetime, timezone
from typing import Any

from app.db.store import get_execution, list_executions, list_operations, list_quant_run_task_records, list_recent_quant_run_task_records
from app.services.backtest_data_source import BacktestDataSource


def _safe_float(value: Any) -> float:
    try:
        return float(value or 0)
    except Exception:
        return 0.0


def _safe_int(value: Any) -> int:
    try:
        return int(value or 0)
    except Exception:
        return 0


def _task_context_by_execution(limit: int) -> dict[int, dict[str, Any]]:
    out: dict[int, dict[str, Any]] = {}
    for record in list_recent_quant_run_task_records(limit=limit):
        execution_id = record.get("execution_id")
        if execution_id is None:
            continue
        detail = {}
        try:
            records = list_quant_run_task_records(int(record["task_id"]), limit=5000)
            detail = next((item.get("detail") or {} for item in records if item.get("id") == record.get("id")), {})
        except Exception:
            detail = {}
        out[int(execution_id)] = {**record, "detail": detail}
    return out


def _operation_row(operation: dict[str, Any], *, close_price: float | None = None) -> dict[str, Any]:
    price = _safe_float(operation.get("price"))
    quantity = _safe_int(operation.get("quantity"))
    fees = {
        "commission": round(_safe_float(operation.get("commission")), 6),
        "transfer_fee": round(_safe_float(operation.get("transfer_fee")), 6),
        "stamp_tax": round(_safe_float(operation.get("stamp_tax")), 6),
    }
    total_fees = round(sum(fees.values()), 6)
    mark_to_market = None
    if close_price and close_price > 0 and price > 0 and quantity > 0:
        side = str(operation.get("side") or "").upper()
        raw = (float(close_price) - price) * quantity
        mark_to_market = round(raw if side == "BUY" else -raw, 4)
    return {
        "operation_id": operation.get("id"),
        "operation_uid": operation.get("operation_uid") or "",
        "execution_id": operation.get("execution_id"),
        "symbol": operation.get("symbol"),
        "name": operation.get("name") or "",
        "side": str(operation.get("side") or "").upper(),
        "quantity": quantity,
        "simulated_price": round(price, 6),
        "trade_time": operation.get("at"),
        "assumption": {
            "price_rule": "T+1 open price plus slippage when generated by quant task; manual trades use submitted price",
            "slippage_bps": round(_safe_float(operation.get("slippage_bps")), 4),
            "fee_schedule_version": operation.get("fee_schedule_version") or "",
            "remark": operation.get("remark") or "",
        },
        "fees": {**fees, "total": total_fees},
        "close_price": round(close_price, 6) if close_price and close_price > 0 else None,
        "mark_to_market_pnl": mark_to_market,
    }


def build_simulation_ledger(*, limit: int = 20, execution_id: int | None = None) -> dict[str, Any]:
    n = max(1, min(int(limit or 20), 100))
    executions = [get_execution(int(execution_id))] if execution_id is not None else list_executions(limit=n)
    executions = [item for item in executions if item]
    context_map = _task_context_by_execution(limit=max(100, n * 5))
    ds = BacktestDataSource()
    items: list[dict[str, Any]] = []
    for execution in executions:
        eid = int(execution.get("id") or 0)
        context = context_map.get(eid) or {}
        signal_date = context.get("signal_date")
        execute_date = context.get("execute_date") or str(execution.get("executed_at") or "")[:10]
        detail = context.get("detail") if isinstance(context.get("detail"), dict) else {}
        operations = list_operations(execution_id=eid, limit=5000)
        close_map: dict[str, float] = {}
        try:
            snap = ds.load_snapshot(str(execute_date or "").replace("-", ""))
            close_map = {str(row.symbol): _safe_float(getattr(row, "close", 0)) for row in snap}
        except Exception:
            close_map = {}
        rows = [_operation_row(op, close_price=close_map.get(str(op.get("symbol") or ""))) for op in sorted(operations, key=lambda x: int(x.get("id") or 0))]
        blocked = []
        actions = detail.get("rebalance_actions") if isinstance(detail.get("rebalance_actions"), dict) else {}
        if actions:
            blocked = list(actions.get("blocked") or [])
        model_payload = detail.get("model") if isinstance(detail.get("model"), dict) else {}
        orders = execution.get("orders") or []
        items.append({
            "execution_id": eid,
            "strategy_id": execution.get("strategy_id"),
            "executed_at": execution.get("executed_at"),
            "signal_date": signal_date,
            "execute_date": execute_date,
            "source": "quant_task" if context else "manual_or_legacy",
            "message": context.get("message") or "",
            "strategy_version": (detail.get("strategy_template") or {}).get("id") or "",
            "model_version": detail.get("model_version") or model_payload.get("version") or "",
            "target_positions": detail.get("target_positions") or [],
            "current_positions_before": detail.get("current_positions") or [],
            "orders": orders,
            "operations": rows,
            "blocked_signals": blocked,
            "summary": {
                "operation_count": len(rows),
                "buy_count": sum(1 for row in rows if row["side"] == "BUY"),
                "sell_count": sum(1 for row in rows if row["side"] == "SELL"),
                "gross_turnover": round(sum(float(row["simulated_price"]) * int(row["quantity"]) for row in rows), 4),
                "total_fees": round(sum(float((row.get("fees") or {}).get("total") or 0) for row in rows), 6),
                "unfilled_count": len([item for item in orders if str(item.get("status") or "").lower() in {"rejected", "unfilled", "blocked"}]),
            },
            "links": {
                "task_run_detail": f"/api/quant-runs/tasks/{context.get('task_id')}/run-detail?execute_date={execute_date}" if context.get("task_id") else None,
                "operations": f"/api/operations?execution_id={eid}",
                "equity_curve": f"/api/equity/strategy-equity-curve?execution_id={eid}",
            },
        })
    return {
        "ok": True,
        "schema_version": "simulation_ledger_v1",
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "items": items,
        "limitations": [
            "mark_to_market_pnl is an execution-day estimate; formal FIFO realized attribution is exposed through decision review outcomes.",
        ],
    }
